def is_generic(summary: str, description: str) -> bool:
    return (
        "に由来する用語。" in summary
        or "に関連する" in summary
        or "ゲームでのニュアンス：\n" in description
        or len(summary.strip()) < 18
    )


def main() -> None:
    backup = DB_PATH.with_name("dictionary.before_real_description_enrichment.sqlite3")
    shutil.copy2(DB_PATH, backup)

    updated = 0
    skipped = 0
    with get_connection(DB_PATH) as conn:
        for row in conn.execute("SELECT * FROM entries ORDER BY id").fetchall():
            entry = dict(row)
            term = entry["term"]
            summary = DESCRIPTIONS.get(term)
            if not summary:
                skipped += 1
                continue
            if not is_generic(entry.get("summary", ""), entry.get("description", "")):
                skipped += 1
                continue

            payload = {field: entry.get(field, "") for field in ENTRY_FIELDS}
            payload["summary"] = summary
            payload["description"] = (
                f"{summary}\n"
                f"由来：{entry.get('mythology') or '伝承'}"
                f"（分類：{entry.get('kind') or '用語'}）。"
            )
            update_entry_in_conn(conn, entry["id"], payload)
            updated += 1

    print({"updated": updated, "skipped": skipped, "backup": str(backup)})


if __name__ == "__main__":
    main()
