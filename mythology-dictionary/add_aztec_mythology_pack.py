def make_description(name: str, kind: str, domains: str, summary: str, note: str, see_also: str) -> str:
    return "\n\n".join(
        [
            summary,
            note,
            (
                f"辞典的には、{name}は「{kind}」として引ける項目で、中心になる属性は「{domains}」。"
                "アステカ神話では神格、方位、暦、祭儀、死後世界、都市の起源が互いに結びついているため、"
                "単なる名前ではなく、どの神話場面・儀礼・世界観の層に関わる語かを合わせて読むと把握しやすい。"
            ),
            (
                "世界観設定で使う場合は、見た目のモチーフだけでなく、雨と農耕、太陽と犠牲、冥界と旅、"
                "双対性と方位、暦と運命のような関係を意識すると、アステカ的な厚みを持たせやすい。"
                f"関連語としては「{see_also}」も一緒に確認すると、神々の役割や神話上の位置づけがつながる。"
            ),
        ]
    )


def term(
    name: str,
    aliases: str,
    kind: str,
    domains: str,
    summary: str,
    note: str,
    see_also: str,
    *,
    reading: str = "",
    language: str = "Nahuatl, Spanish",
    tags: str = "",
) -> dict[str, str]:
    return {
        "term": name,
        "reading": reading,
        "aliases": aliases,
        "language": language,
        "kind": kind,
        "mythology": "アステカ",
        "domains": domains,
        "tags": merge_multi_values("アステカ神話, メソアメリカ, 実在神話", tags, TAG),
        "summary": summary,
        "description": make_description(name, kind, domains, summary, note, see_also),
        "see_also": see_also,
        "sources": SOURCE_NOTE,
    }


