def main() -> None:
    entries = [make_entry(item) for item in DEMONS]
    OUT_PATH.write_text(json.dumps(entries, ensure_ascii=False, indent=2), encoding="utf-8")
    shutil.copy2(DB_PATH, BACKUP_PATH)

    created = 0
    updated = 0
    with get_connection(DB_PATH) as conn:
        for entry in entries:
            matches = find_entries_by_term_in_conn(conn, entry["term"])
            if matches:
                existing = matches[0]
                payload = {field: entry[field] for field in ENTRY_FIELDS}
                payload["aliases"] = merge_multi_values(existing.get("aliases", ""), entry["aliases"])
                payload["tags"] = merge_multi_values(existing.get("tags", ""), entry["tags"])
                payload["sources"] = merge_multi_values(existing.get("sources", ""), entry["sources"])
                update_entry_in_conn(conn, existing["id"], payload)
                updated += 1
            else:
                insert_entry(conn, entry)
                created += 1

    print({"created": created, "updated": updated, "total_goetia": len(entries), "backup": str(BACKUP_PATH), "export": str(OUT_PATH)})


